"""Module 5 — rescue options A–E (ROZWIAZANIE.md §10).

Options are generated by code. Each option is a set of events to add and/or date changes to existing events;
its effect is obtained by re-running the very same forecast and risk code, never by a shortcut formula.
"""
from __future__ import annotations

from dataclasses import dataclass, replace
from datetime import date, timedelta
from decimal import ROUND_CEILING, Decimal
from typing import Callable, Optional, Sequence

from categories import CATEGORIES
from config import (
    BANK_NAME,
    CREDIT_LINE_INTEREST_RATE,
    CREDIT_LINE_ROUNDING_EUR,
    CREDIT_LINE_TERM_DAYS,
    DAYS_PER_YEAR,
    DEFERRAL_MONTHS,
    SHORT_CLOSURE_DAYS,
    UNARRANGED_OVERDRAFT_RATE,
)
from domain import (
    EventDraft,
    EventType,
    EventUpdate,
    ForecastDay,
    ItemKind,
    PlannedEvent,
    RescueOption,
    RiskStatus,
    RiskWindow,
    Scenario,
)
from events import add_months
from kpi_engine.money import ZERO, cents
from texts import format_day, format_eur, format_period

Simulate = Callable[[Sequence[EventDraft]], Scenario]

_STATUS_RANK = {RiskStatus.GREEN: 0, RiskStatus.YELLOW: 1, RiskStatus.RED: 2}

# Non-financial "pain" used as the last tie-breaker of the code ranking (lower = easier for the owner).
_PAIN_NONE, _PAIN_RESCHEDULE, _PAIN_FAMILY_TALK, _PAIN_LESS_HOLIDAY = 0, 1, 2, 3


@dataclass(frozen=True)
class OptionContext:
    as_of: date
    buffer_eur: Decimal
    events: tuple[PlannedEvent, ...]
    baseline: Scenario
    simulate: Simulate
    rejected_ids: frozenset[str] = frozenset()


@dataclass(frozen=True)
class _Proposal:
    id: str
    title: str
    description: str
    non_financial_cost: Optional[str]
    simulated_actions: tuple[str, ...]
    pain_rank: int
    events_to_add: tuple[EventDraft, ...] = ()
    event_updates: tuple[EventUpdate, ...] = ()

    @property
    def adds_credit_line(self) -> bool:
        return any(event.event_type is EventType.CREDIT_LINE for event in self.events_to_add)


def build_options(context: OptionContext) -> tuple[RescueOption, ...]:
    """All applicable options, each re-simulated. Empty when the baseline is already GREEN."""
    if context.baseline.risk.status is RiskStatus.GREEN:
        return ()
    builders = (_credit_line, _defer_payments, _shorter_closure, _move_expenses, _deferral_plus_credit_line)
    proposals = (builder(context) for builder in builders)
    return tuple(_evaluate(context, proposal) for proposal in proposals if proposal is not None)


def recommend(options: Sequence[RescueOption]) -> Optional[str]:
    """Code ranking: GREEN outcomes first, then lowest cost in EUR, then the least painful trade-off."""
    candidates = [option for option in options if not option.rejected]
    if not candidates:
        return None
    best = min(candidates, key=lambda o: (_STATUS_RANK[o.new_status], o.cost_eur, o.pain_rank, o.id))
    return best.id


def apply_changes(events: Sequence[EventDraft], events_to_add: Sequence[EventDraft],
                  event_updates: Sequence[EventUpdate]) -> tuple[EventDraft, ...]:
    """The event list as it would look after an option is approved."""
    updates = {update.event_id: update for update in event_updates}
    changed = [_with_update(event, updates) for event in events]
    return (*changed, *events_to_add)


def financing_cost(days: Sequence[ForecastDay]) -> Decimal:
    """Interest within the horizon: the credit-line rate up to the arranged limit, the overdraft rate beyond it."""
    total = ZERO
    for day in days:
        overdrawn = max(ZERO, -day.balance_eur)
        arranged = min(overdrawn, -day.floor_eur)
        total += arranged * CREDIT_LINE_INTEREST_RATE + (overdrawn - arranged) * UNARRANGED_OVERDRAFT_RATE
    return cents(total / DAYS_PER_YEAR)


def unarranged_overdraft_cost(days: Sequence[ForecastDay]) -> Decimal:
    """What the same negative balances would cost with no arranged credit line (comparison figure)."""
    overdrawn_total = sum((max(ZERO, -day.balance_eur) for day in days), ZERO)
    return cents(overdrawn_total * UNARRANGED_OVERDRAFT_RATE / DAYS_PER_YEAR)


def required_credit_limit(scenario: Scenario, buffer_eur: Decimal) -> Decimal:
    """Additional limit that restores the buffer: (−headroom + buffer) rounded up to the next 5,000 EUR."""
    needed = buffer_eur - scenario.risk.headroom_eur
    steps = (needed / CREDIT_LINE_ROUNDING_EUR).to_integral_value(rounding=ROUND_CEILING)
    return max(steps, Decimal(1)) * CREDIT_LINE_ROUNDING_EUR


def _with_update(event: EventDraft, updates: dict[int, EventUpdate]) -> EventDraft:
    update = updates.get(event.id) if isinstance(event, PlannedEvent) else None
    if update is None:
        return event
    return replace(event, date_from=update.date_from, date_to=update.date_to)


def _evaluate(context: OptionContext, proposal: _Proposal) -> RescueOption:
    scenario = context.simulate(apply_changes(context.events, proposal.events_to_add, proposal.event_updates))
    cost = financing_cost(scenario.forecast.days)
    return RescueOption(
        id=proposal.id,
        title=proposal.title,
        description=proposal.description,
        cost_eur=cost,
        cost_note=_cost_note(proposal, scenario, cost),
        non_financial_cost=proposal.non_financial_cost,
        simulated_actions=proposal.simulated_actions,
        events_to_add=proposal.events_to_add,
        event_updates=proposal.event_updates,
        scenario=scenario,
        pain_rank=proposal.pain_rank,
        rejected=proposal.id in context.rejected_ids,
    )


def _cost_note(proposal: _Proposal, scenario: Scenario, cost: Decimal) -> Optional[str]:
    if proposal.adds_credit_line:
        comparison = unarranged_overdraft_cost(scenario.forecast.days)
        return (f"Interest at {_percent(CREDIT_LINE_INTEREST_RATE)} p.a. (assumed rate) on the amount actually used "
                f"within the forecast horizon. An unarranged overdraft at {_percent(UNARRANGED_OVERDRAFT_RATE)} p.a. "
                f"would cost about {format_eur(comparison)} for the same shortfall.")
    if cost > 0:
        return (f"The step itself is free, but the account would still be overdrawn: about {format_eur(cost)} "
                f"of overdraft interest within the forecast horizon.")
    return None


def _percent(rate: Decimal) -> str:
    return f"{(rate * 100).normalize():f}%"


# --------------------------------------------------------------------------- A: credit line

def _credit_line(context: OptionContext) -> _Proposal:
    event = _credit_line_event(context, context.baseline)
    return _Proposal(
        id="A",
        title="Credit line",
        description=(f"Arrange a {format_eur(event.amount_eur)} credit line with {BANK_NAME}. You only pay interest "
                     f"on the amount you actually use, and the {format_eur(context.buffer_eur)} buffer stays intact."),
        non_financial_cost=None,
        simulated_actions=(_credit_line_action(event),),
        pain_rank=_PAIN_NONE,
        events_to_add=(event,),
    )


def _credit_line_event(context: OptionContext, scenario: Scenario) -> EventDraft:
    limit = required_credit_limit(scenario, context.buffer_eur)
    start = context.as_of + timedelta(days=1)
    return EventDraft(
        event_type=EventType.CREDIT_LINE,
        date_from=start,
        date_to=start + timedelta(days=CREDIT_LINE_TERM_DAYS),
        amount_eur=limit,
        description=f"Credit line of {format_eur(limit)} with {BANK_NAME}",
    )


def _credit_line_action(event: EventDraft) -> str:
    return f"Credit line request for {format_eur(event.amount_eur)} sent to {BANK_NAME} (simulated)."


# --------------------------------------------------------------------------- B: postpone deferrable payments

@dataclass(frozen=True)
class _DeferrablePayment:
    day: date
    category: str
    amount_eur: Decimal  # positive


def _defer_payments(context: OptionContext) -> Optional[_Proposal]:
    window = context.baseline.risk.risk_window
    payments = _deferrable_payments(context.baseline, window)
    if window is None or not payments:
        return None
    categories = sorted({payment.category for payment in payments})
    labels = " and ".join(_lower_first(CATEGORIES[key].label) for key in categories)
    total = sum((payment.amount_eur for payment in payments), ZERO)
    return _Proposal(
        id="B",
        title=f"Postpone the {labels}",
        description=(f"Postpone {_count(len(payments), 'payment')} ({format_eur(total)} in total) due before the "
                     f"low point by {DEFERRAL_MONTHS} months. The money is still owed — it is paid later."),
        non_financial_cost=_deferral_trade_off(categories),
        simulated_actions=tuple(_deferral_action(payment) for payment in payments),
        pain_rank=_PAIN_FAMILY_TALK,
        events_to_add=tuple(_deferral_event(key, window) for key in categories),
    )


def _deferrable_payments(scenario: Scenario, window: Optional[RiskWindow]) -> list[_DeferrablePayment]:
    if window is None:
        return []
    return [
        _DeferrablePayment(day.date, item.category, -item.amount_eur)
        for day in scenario.forecast.days if window.start <= day.date <= window.end
        for item in day.items if item.kind is ItemKind.FIXED and CATEGORIES[item.category].deferrable
    ]


def _deferral_event(category: str, window: RiskWindow) -> EventDraft:
    return EventDraft(
        event_type=EventType.PAYMENT_DEFERRAL,
        date_from=window.start,
        date_to=window.end,
        category=category,
        description=f"{CATEGORIES[category].label}: payments postponed by {DEFERRAL_MONTHS} months",
    )


def _deferral_action(payment: _DeferrablePayment) -> str:
    new_day = add_months(payment.day, DEFERRAL_MONTHS)
    return (f"{CATEGORIES[payment.category].label}: payment of {format_day(payment.day)} postponed to "
            f"{format_day(new_day)} (simulated).")


def _deferral_trade_off(categories: Sequence[str]) -> str:
    if categories == ["investment_outflow"]:
        return "a conversation with your brother Luigi"
    return "an agreement with the recipients of the postponed payments"


# --------------------------------------------------------------------------- C: shorter closure

def _shorter_closure(context: OptionContext) -> Optional[_Proposal]:
    closure = _longest_upcoming_closure(context)
    if closure is None:
        return None
    new_end = closure.date_from + timedelta(days=SHORT_CLOSURE_DAYS - 1)
    days_given_up = (closure.date_to - new_end).days
    reopening = new_end + timedelta(days=1)
    return _Proposal(
        id="C",
        title="Shorter closure",
        description=(f"Close for {SHORT_CLOSURE_DAYS} days only ({format_period(closure.date_from, new_end)}) "
                     f"and reopen on {format_day(reopening)} instead of "
                     f"{format_day(closure.date_to + timedelta(days=1))}."),
        non_financial_cost=f"{_count(days_given_up, 'day')} less holiday",
        simulated_actions=(f"Closure shortened to {format_period(closure.date_from, new_end)}; reopening on "
                           f"{format_day(reopening)} (simulated).",),
        pain_rank=_PAIN_LESS_HOLIDAY,
        event_updates=(EventUpdate(closure.id, closure.date_from, new_end),),
    )


def _longest_upcoming_closure(context: OptionContext) -> Optional[PlannedEvent]:
    last_day = context.baseline.forecast.days[-1].date
    closures = [
        event for event in context.events
        if event.event_type is EventType.CLOSURE and context.as_of < event.date_from <= last_day
        and _length_days(event) > SHORT_CLOSURE_DAYS
    ]
    return max(closures, key=lambda event: (_length_days(event), -event.date_from.toordinal(), -event.id),
               default=None)


def _length_days(event: EventDraft) -> int:
    return (event.date_to - event.date_from).days + 1


# --------------------------------------------------------------------------- D: move planned expenses

def _move_expenses(context: OptionContext) -> Optional[_Proposal]:
    window = context.baseline.risk.risk_window
    if window is None:
        return None
    expenses = [event for event in context.events
                if event.event_type is EventType.EXPENSE and window.start <= event.date_from <= window.end]
    if not expenses:
        return None
    new_day = window.end + timedelta(days=1)
    total = sum((event.amount_eur or ZERO for event in expenses), ZERO)
    return _Proposal(
        id="D",
        title="Postpone the planned expense" if len(expenses) == 1 else "Postpone the planned expenses",
        description=(f"Move {_count(len(expenses), 'planned expense')} ({format_eur(total)} in total) to "
                     f"{format_day(new_day)}, just after the low point."),
        non_financial_cost="the purchase happens later than planned",
        simulated_actions=tuple(
            f"Planned expense \"{event.description}\" moved from {format_day(event.date_from)} to "
            f"{format_day(new_day)} (simulated)." for event in expenses),
        pain_rank=_PAIN_RESCHEDULE,
        event_updates=tuple(EventUpdate(event.id, new_day, new_day) for event in expenses),
    )


# --------------------------------------------------------------------------- E: B + smaller credit line

def _deferral_plus_credit_line(context: OptionContext) -> Optional[_Proposal]:
    deferral = _defer_payments(context)
    if deferral is None:
        return None
    after_deferral = context.simulate(apply_changes(context.events, deferral.events_to_add, ()))
    if after_deferral.risk.status is RiskStatus.GREEN:
        return None  # postponing alone is enough; a credit line on top would add nothing
    credit_line = _credit_line_event(context, after_deferral)
    return _Proposal(
        id="E",
        title="Postpone payments + smaller credit line",
        description=(f"{deferral.description} Cover what is still missing with a smaller "
                     f"{format_eur(credit_line.amount_eur)} credit line with {BANK_NAME}."),
        non_financial_cost=deferral.non_financial_cost,
        simulated_actions=(_credit_line_action(credit_line), *deferral.simulated_actions),
        pain_rank=_PAIN_FAMILY_TALK,
        events_to_add=(*deferral.events_to_add, credit_line),
    )


def _count(number: int, noun: str) -> str:
    return f"{number} {noun}{'' if number == 1 else 's'}"


def _lower_first(text: str) -> str:
    return text[:1].lower() + text[1:]
