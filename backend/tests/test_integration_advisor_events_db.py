"""The planned-event types of the CFO advisors (term_deposit, fx_prebuy) against a real PostgreSQL: the widened
check in db/schema.sql, its migration of an older database, and the round trip through PostgresRepository.

Runs only when KPI_TEST_DATABASE_URL is set; everything happens in throw-away schemas (see test_integration_db.py).
"""
import uuid
from datetime import date
from decimal import Decimal

import pytest

import service
from conftest import REPO
from domain import DashboardQuery, DecisionStatus, EventDraft, EventSource, EventType, NewDecision
from repository import FINGERPRINT_KEY, PostgresRepository
from test_integration_db import DSN, schema  # noqa: F401  (pytest fixture)

pytestmark = pytest.mark.skipif(not DSN, reason="KPI_TEST_DATABASE_URL not set")

psycopg = pytest.importorskip("psycopg")

SCHEMA_SQL = (REPO / "db" / "schema.sql").read_text(encoding="utf-8")
OCTOBER_15 = DashboardQuery(date(2025, 10, 15), 60, Decimal("3000"))
TAX_RESERVE = EventDraft(event_type=EventType.TERM_DEPOSIT, date_from=date(2025, 10, 16), date_to=date(2025, 11, 16),
                         amount_eur=Decimal("9000.00"), category="tax_reserve", description="Tax reserve deposit")
FX_PREBUY = EventDraft(event_type=EventType.FX_PREBUY, date_from=date(2025, 10, 16), date_to=date(2025, 12, 15),
                       amount_eur=Decimal("8716.67"), description="CHF bought for the remaining Zurich instalments")

INSERT_EVENT = """INSERT INTO planned_events (event_type, date_from, date_to, amount_eur, category, description,
                                              source, as_of_date)
                  VALUES (%s, '2025-10-16', '2025-11-16', %s, %s, %s, %s, '2025-10-15')"""
EVENT_TYPE_CHECKS = """SELECT conname, pg_get_constraintdef(oid) FROM pg_constraint
                       WHERE conrelid = 'planned_events'::regclass AND contype = 'c'
                         AND pg_get_constraintdef(oid) LIKE '%%credit_line%%'"""
# The inline check of databases created before the advisors existed; PostgreSQL names it itself.
LEGACY_CHECK = """ALTER TABLE planned_events DROP CONSTRAINT planned_events_event_type;
                  ALTER TABLE planned_events ADD CHECK (
                      event_type IN ('closure', 'expense', 'inflow', 'payment_deferral', 'credit_line'))"""
LEGACY_ROWS = (("closure", None, None, "Legacy closure", "chat"), ("expense", 8000, None, "Legacy oven", "chat"),
               ("inflow", 500, None, "Legacy inflow", "chat"),
               ("payment_deferral", 3975, "investment_outflow", "Legacy deferral", "agent"),
               ("credit_line", 20000, None, "Legacy credit line", "agent"))


@pytest.fixture
def connection(schema):  # noqa: F811
    conn = psycopg.connect(DSN, options=f"-c search_path={schema}", autocommit=True)
    yield conn
    conn.execute("DELETE FROM planned_events")
    conn.execute("DELETE FROM owner_decisions")
    conn.close()


@pytest.fixture
def legacy_connection():
    """An empty database as it looked before term_deposit and fx_prebuy existed, with rows of every old type."""
    name = f"kpi_test_{uuid.uuid4().hex[:10]}"
    conn = psycopg.connect(DSN, autocommit=True)
    conn.execute(f"CREATE SCHEMA {name}")
    conn.execute(f"SET search_path TO {name}")
    conn.execute(SCHEMA_SQL)
    conn.execute(LEGACY_CHECK)
    for row in LEGACY_ROWS:
        conn.execute(INSERT_EVENT, row)
    yield conn
    conn.execute(f"DROP SCHEMA {name} CASCADE")
    conn.close()


def _stored_rows(conn) -> list[tuple]:
    return conn.execute("SELECT * FROM planned_events ORDER BY id").fetchall()


def _decision(proposal_id: str, title: str) -> NewDecision:
    snapshot = {FINGERPRINT_KEY: f"fingerprint-{proposal_id}", "status_before": "GREEN",
                "min_balance_before_eur": 20000.0, "min_balance_date_before": "2025-10-16", "status_after": "GREEN",
                "min_balance_after_eur": 4500.0, "credit_limit_after_eur": None, "cost_eur": 0.0}
    return NewDecision(as_of_date=OCTOBER_15.as_of_date, horizon_days=OCTOBER_15.horizon_days,
                       buffer_eur=OCTOBER_15.buffer_eur, option_id=proposal_id, option_title=title,
                       option_description=f"{title}.", status=DecisionStatus.APPROVED, llm_explanation=None,
                       execution_messages=(f"{title} (simulated).",), forecast_snapshot=snapshot)


# --- the migration of an older database ---------------------------------------------------------------------

def test_a_legacy_database_rejects_the_new_types_until_the_schema_is_applied(legacy_connection):
    [(name, _)] = legacy_connection.execute(EVENT_TYPE_CHECKS).fetchall()
    assert name == "planned_events_event_type_check"  # generated by PostgreSQL, never written in a script
    with pytest.raises(psycopg.errors.CheckViolation):
        legacy_connection.execute(INSERT_EVENT, ("term_deposit", 9000, "tax_reserve", "Tax reserve", "agent"))


def test_the_schema_script_widens_the_check_and_can_run_again(legacy_connection):
    rows_before = _stored_rows(legacy_connection)
    for _ in range(2):
        legacy_connection.execute(SCHEMA_SQL)
        [(name, definition)] = legacy_connection.execute(EVENT_TYPE_CHECKS).fetchall()
        assert name == "planned_events_event_type"
        assert "'term_deposit'" in definition and "'fx_prebuy'" in definition
    assert _stored_rows(legacy_connection) == rows_before
    legacy_connection.execute(INSERT_EVENT, ("term_deposit", 9000, "tax_reserve", "Tax reserve", "agent"))
    legacy_connection.execute(INSERT_EVENT, ("term_deposit", 12000, "investment", "Investment", "agent"))
    legacy_connection.execute(INSERT_EVENT, ("fx_prebuy", 8716.67, None, "CHF bought in advance", "agent"))
    for row in LEGACY_ROWS:
        legacy_connection.execute(INSERT_EVENT, row)
    assert len(_stored_rows(legacy_connection)) == 2 * len(LEGACY_ROWS) + 3


def test_after_the_migration_unknown_types_and_chat_rows_of_the_new_types_are_refused(legacy_connection):
    legacy_connection.execute(SCHEMA_SQL)
    with pytest.raises(psycopg.errors.CheckViolation, match="planned_events_event_type"):
        legacy_connection.execute(INSERT_EVENT, ("bond_purchase", 100, None, "Unknown", "agent"))
    for event_type in ("term_deposit", "fx_prebuy"):
        with pytest.raises(psycopg.errors.CheckViolation, match="planned_events_chat_scope"):
            legacy_connection.execute(INSERT_EVENT, (event_type, 100, None, "From the chat", "chat"))


# --- the repository -----------------------------------------------------------------------------------------

def test_advisor_decisions_and_their_events_round_trip(connection):
    repository = PostgresRepository(connection)
    records = repository.record_decisions([
        (_decision("T1", "Tax reserve deposit"), (TAX_RESERVE,)),
        (_decision("T2", "Raise the tax prepayments"), ()),
        (_decision("F1", "Buy the Swiss francs now"), (FX_PREBUY,)),
    ])
    assert [record.option_id for record in records] == ["T1", "T2", "F1"]
    assert [decision.option_id for decision in repository.list_decisions()] == ["F1", "T2", "T1"]
    stored = sorted(repository.list_events(), key=lambda event: event.id)
    assert [(event.event_type, event.category, event.amount_eur, event.date_from, event.date_to, event.source,
             event.decision_id) for event in stored] == [
        (EventType.TERM_DEPOSIT, "tax_reserve", Decimal("9000.00"), date(2025, 10, 16), date(2025, 11, 16),
         EventSource.AGENT, records[0].id),
        (EventType.FX_PREBUY, None, Decimal("8716.67"), date(2025, 10, 16), date(2025, 12, 15),
         EventSource.AGENT, records[2].id)]


def test_the_forecast_from_the_database_applies_the_stored_advisor_events(connection):
    repository = PostgresRepository(connection)
    baseline = service.build_dashboard(repository, OCTOBER_15)
    repository.record_decisions([(_decision("T1", "Tax reserve deposit"), (TAX_RESERVE,)),
                                 (_decision("F1", "Buy the Swiss francs now"), (FX_PREBUY,))])
    dashboard = service.build_dashboard(repository, OCTOBER_15)
    assert {event.event_type for event in dashboard.events} == {EventType.TERM_DEPOSIT, EventType.FX_PREBUY}
    opening_day = dashboard.forecast.days[0]
    assert opening_day.date == date(2025, 10, 16)
    assert {"term_deposit", "fx_prebuy"} <= {item.category for item in opening_day.items}
    assert opening_day.balance_eur < baseline.forecast.days[0].balance_eur


def test_withdrawing_the_decision_removes_its_term_deposit(connection):
    repository = PostgresRepository(connection)
    repository.record_decisions([(_decision("T1", "Tax reserve deposit"), (TAX_RESERVE,))])
    [deposit] = repository.list_events()
    service.delete_event(repository, deposit.id)
    assert repository.list_events() == []
    assert repository.list_decisions()[0].withdrawn_at is not None
